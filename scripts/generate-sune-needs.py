#!/usr/bin/env python3
"""Regenerate src/v2/rules/sune-v1-needs.ts from ArchitectureDocs sune_v1.py.

Usage (from the Norse-API root):
  python3 scripts/generate-sune-needs.py [--arch-docs ../ArchitectureDocs] [--ref origin/main]
  npx prettier --write src/v2/rules/sune-v1-needs.ts

Reads proposed-changes/sune/v1/ at --ref with `git show` (the working tree of
ArchitectureDocs is never read). Codes follow build_v1_xlsx.py: Tier 2 code =
Tier 1 code + "-" + 2-digit counter in file order. Each entry carries the
display name AND the description: the Tier 2 "Spoken Description", or the
Tier 1 definition. Rows are keyed by code, never by display name (display
names repeat, e.g. N-DIS and N-DIS-01).
"""
import argparse, os, subprocess, sys, tempfile

FILES = ["sune_v1.py", "draft-1-extract.json"]
BASE = "proposed-changes/sune/v1"


def load(arch, ref):
    tmp = tempfile.mkdtemp(prefix="sune-v1-")
    for f in FILES:
        data = subprocess.check_output(["git", "-C", arch, "show", f"{ref}:{BASE}/{f}"])
        with open(os.path.join(tmp, f), "wb") as fh:
            fh.write(data)
    ns = {"__file__": os.path.join(tmp, "sune_v1.py"), "__name__": "sune_v1"}
    with open(ns["__file__"]) as fh:
        exec(compile(fh.read(), ns["__file__"], "exec"), ns)
    return ns["T1"], ns["N"]


def q(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def entry(code, name, display, description, tier1=None):
    lines = [
        "  {",
        f"    code: {q(code)},",
        f"    name: {q(name)},",
        f"    display: {q(display)},",
        f"    description: {q(description)},",
    ]
    if tier1:
        lines.append(f"    tier1: {q(tier1)},")
    lines.append("  },")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--arch-docs", default=os.path.join(os.path.dirname(__file__), "..", "..", "ArchitectureDocs"))
    ap.add_argument("--ref", default="origin/main")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(__file__), "..", "src", "v2", "rules", "sune-v1-needs.ts"))
    a = ap.parse_args()
    t1, n = load(a.arch_docs, a.ref)
    counter, t2 = {}, []
    for r in n:
        i = counter.get(r["tier1"], 0) + 1
        counter[r["tier1"]] = i
        t2.append((f'{r["tier1"]}-{i:02d}', r))
    codes = [c for c, *_ in t1] + [c for c, _ in t2]
    assert len(set(codes)) == len(codes), "duplicate code"
    for c, name, display, definition, _ in t1:
        assert display.strip() and definition.strip(), c
    for c, r in t2:
        assert r["display"].strip() and r["spoken"].strip(), c
    out = [
        "// SUNE v1 need list, GENERATED by scripts/generate-sune-needs.py from ArchitectureDocs",
        "// proposed-changes/sune/v1/sune_v1.py. Do not edit by hand: change sune_v1.py, rerun the script.",
        "// Codes follow build_v1_xlsx.py. `description` is the spoken description (Tier 2) or the",
        "// definition (Tier 1). Join by code, never by display name. Matches the 91 labels of the Hydra needs model.",
        "// A .ts module, not .json: nest build (tsc) does not copy JSON files to dist.",
        "",
        "export interface SuneEntry {",
        "  code: string;",
        "  name: string;",
        "  display: string;",
        "  /** Spoken description (Tier 2) or definition (Tier 1), ADR 0039 Decision 31. */",
        "  description: string;",
        "  tier1?: string;",
        "}",
        "",
        "export const SUNE_VERSION = 'v1';",
        "",
        "export const SUNE_TIER1: readonly SuneEntry[] = [",
    ]
    out += [entry(c, name, d, df) for c, name, d, df, _ in t1]
    out += ["];", "", "export const SUNE_TIER2: readonly SuneEntry[] = ["]
    out += [entry(c, r["name"], r["display"], r["spoken"], r["tier1"]) for c, r in t2]
    out += ["];", ""]
    with open(a.out, "w") as fh:
        fh.write("\n".join(out))
    print(f"wrote {a.out}: {len(t1)} Tier 1, {len(t2)} Tier 2", file=sys.stderr)


if __name__ == "__main__":
    main()
